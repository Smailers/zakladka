//! Форма значка — лента-закладка с вырезом внизу (P 590–603). Одна на значок трея
//! (`core::color::icon_pixels`) и значок файла Zakladka.exe: build.rs подключает этот файл через
//! `#[path]`, поэтому здесь нет зависимостей от остального кода.

/// Точка (u, v) в долях стороны квадрата (0…1, v — сверху вниз) лежит на ленте.
pub fn inside(u: f64, v: f64) -> bool {
    let mut inside = (0.25..=0.75).contains(&u) && (0.06..=0.94).contains(&v);
    if inside && v > 0.66 && (u - 0.5).abs() < (v - 0.66) * 0.9 {
        inside = false;
    }
    inside
}
